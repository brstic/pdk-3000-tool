#!/usr/bin/env python3
"""Generate PdkToolWin/platforms.h (level-1 data for 911 991/981/718 and 918 Spyder) from <p>_bytes.json.
Usage: python3 -I gen_platforms_h.py <platforms dir> <G1 dtc_table.h> <out platforms.h> [--no-de]"""
import json, re, sys
D, G1H, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
NO_DE = '--no-de' in sys.argv
g1 = {}
for l in open(G1H, encoding='utf-8'):
    m = re.match(r'  \{0x[0-9A-F]+,"(\w+)","((?:[^"\\]|\\.)*)"', l)
    if m: g1[m.group(1)] = m.group(2)
EN = {  # own translations of the codes that the 970 catalogue does not have
 'P0164':'TCU data/software does not match the engine','P0602':'TCU not programmed',
 'P0634':'TCU over-temperature (hot mode)','P0691':'Solenoid valve MV3 (KSM)','P0692':'Solenoid valve MV3 (KSP / OL)',
 'P0761':'Multiplexer valve MUX1 stuck at minus','P0762':'Multiplexer valve MUX1 stuck at plus',
 'P0766':'Multiplexer valve MUX2 stuck at minus','P0767':'Multiplexer valve MUX2 stuck at plus',
 'P0771':'Multiplexer valve MUX3 stuck at minus','P0772':'Multiplexer valve MUX3 stuck at plus',
 'P1636':'CAN message timeout: airbag','P172B':'Gearbox oil temperature sensor gradient error / slow drift',
 'P1762':'Engaged gears conflict with the driver\'s direction request and cannot be disengaged (front-axle e-machine OK)',
 'P17C0':'CAN signal error: airbag','P17C1':'Rear-axle e-machine drive interrupted after crash',
 'P17F5':'Gearbox over-temperature, gear set','P185A':'Shadow fault: MUX1 stuck at minus','P1875':'Tyre circumference implausible',
 'P1995':'No idle-speed increase in hybrid driving','P199A':'Engine torque values inaccurate',
 'U0114':'CAN message timeout: AWD control unit','U0134':'CAN message timeout: rear-axle steering',
 'U0164':'CAN message timeout: climate control unit','U0414':'CAN signal error: AWD','U0422':'CAN signal error: gateway',
 'U0435':'CAN signal error: rear-axle steering','U071A':'CAN timeout: door control unit','U171A':'CAN timeout: door control unit',
}
def c(s):
    for a,b in (('ä','ae'),('ö','oe'),('ü','ue'),('Ä','Ae'),('Ö','Oe'),('Ü','Ue'),('ß','ss')): s=s.replace(a,b)
    s=s.encode('ascii','replace').decode()
    return s.replace('\\', '\\\\').replace('"', '\\"').strip()
def code16(p):
    return ({'P':0,'C':1,'B':2,'U':3}[p[0]] << 14) | int(p[1:], 16)
out = ['// platforms.h - level-1 support (PIWIS database, no firmware RE) for other PDK TCUs. GENERATED by',
       '// platforms/gen_platforms_h.py. Same KWP2000 services, CAN 0x70F/0x779 and routine LIDs as the 970',
       '// (verified in the database). Condition texts are the ZF texts from the database.',
       '#pragma once', '#include <cstdint>',
       'struct PlatDtc { uint16_t code; const char *pcode; const char *en; const char *de; };',
       'struct PlatCond { int bit; const char *text; };']
def conds(d, key):
    return d['routines'][key].get('conditions', [])
src = {}
for tag, p in (('9X1', '9x1'), ('918', '918S')):
    d = json.load(open(f'{D}/{p}_bytes.json')); src[tag] = d
    # 9x1 and CS1 decode identically; merge CS1 codes into 9X1 anyway
    dt = {e['code']: e['de'] for e in d['dtcs']}
    if tag == '9X1':
        for e in json.load(open(f'{D}/CS1_bytes.json'))['dtcs']: dt.setdefault(e['code'], e['de'])
    out.append(f'static const PlatDtc DTC_{tag}[] = {{')
    miss = []
    for code in sorted(dt, key=code16):
        en = g1.get(code) or EN.get(code)
        if en and code in g1:   # drop 970-firmware details that are not known for this TCU
            en = re.sub(r' \((?:duty outside 8\.\.92 %|TCU expects[^)]*)\)', '', en)
        if not en: miss.append(code); en = c(dt[code])
        de = '' if NO_DE else c(dt[code])
        out.append(f'  {{0x{code16(code):04X},"{code}","{en}","{de}"}},')
    out.append('};')
    if miss: print(tag, 'untranslated:', miss)
for tag in ('9X1', '918'):
    d = src[tag]
    # 918S clutch conditions in the database are a copy of the hydraulics list -> use the 911 list
    for key, nm in (('teach_in_shift_rods', 'RODS'), ('teach_in_clutches', 'CLUTCH'), ('teach_in_hydraulics', 'HYDR')):
        lst = conds(src['9X1'] if (tag == '918' and nm == 'CLUTCH') else d, key)
        out.append(f'static const PlatCond COND_{tag}_{nm}[] = {{')
        out += [f'  {{{x["bit"]},"{c(x["text_de"])}"}},' for x in lst]
        out.append('};')
out.append('#define PLAT_N(a) (int)(sizeof(a)/sizeof((a)[0]))')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('written', OUT, {k: len(src[k]['dtcs']) for k in src})
